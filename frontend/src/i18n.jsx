function storedLang() {
  try {
    const value = localStorage.getItem('jaanch-lang');
    if (value === 'en' || value === 'hi') return value;
  } catch {
    // storage may be blocked
  }
  return 'en';
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(storedLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next) => {
    setLangState(next);
    try {
      localStorage.setItem('jaanch-lang', next);
    } catch {
      // ignore
    }
  }, []);

  const value = useMemo(
    () => ({ lang, setLang, t: (key) => STRINGS[lang][key] ?? STRINGS.en[key] ?? key }),
    [lang, setLang],
  );
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useI18n = () => useContext(LangContext);
